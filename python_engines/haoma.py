# 五行颜色
WUXING_COLOR = {"木":"绿","火":"红","土":"黄","金":"白","水":"黑"}

# 最佳尾数
BEST_TAIL = {
    "水":["1","6"],"火":["2","7"],"木":["3","8"],"金":["4","9"],"土":["5","0"]
}


def extract_digits(number_str):
    """提取数字(去除非数字字符)"""
    return ''.join(c for c in number_str if c.isdigit())


def get_single_shuli(num):
    """单个数字对应的81数理解释"""
    # 先取后4位再求和到1-81
    tail = num[-4:]
    s = sum(int(d) for d in tail)
    while s > 81:
        s = sum(int(d) for d in str(s))
    return SHULI.get(s, ("未知","",""))


def analyze_number(number_str):
    """分析号码"""
    digits = extract_digits(number_str)
    if not digits:
        return {"error": "未找到有效数字"}

    # 1. 总体数理 (号码总和)
    total = sum(int(d) for d in digits)
    while total > 81:
        total = sum(int(d) for d in str(total))

    total_info = SHULI.get(total, SHULI[1])

    # 2. 后四位分析
    tail = digits[-4:] if len(digits) >= 4 else digits
    tail_sum = sum(int(d) for d in tail)
    while tail_sum > 81:
        tail_sum = sum(int(d) for d in str(tail_sum))
    tail_info = SHULI.get(tail_sum, SHULI[1])

    # 3. 五行分析
    last_digit = digits[-1]
    wuxing = ""
    if last_digit in '16':
        wuxing = "水"
    elif last_digit in '27':
        wuxing = "火"
    elif last_digit in '38':
        wuxing = "木"
    elif last_digit in '49':
        wuxing = "金"
    else:
        wuxing = "土"

    # 4. 尾数吉凶
    tail_best = last_digit in BEST_TAIL.get(wuxing, [])

    # 5. 重复数字
    repeating = {}
    for d in set(digits):
        cnt = digits.count(d)
        if cnt >= 3:
            repeating[d] = cnt

    # 6. 总分评定
    score = 50
    if "大吉" in total_info[0]:
        score += 20
    elif "凶" in total_info[0]:
        score -= 15

    if "大吉" in tail_info[0]:
        score += 20
    elif "凶" in tail_info[0]:
        score -= 15

    if tail_best:
        score += 10

    if repeating:
        if max(repeating.values()) >= 5:
            score += 5  # 豹子号
        elif max(repeating.values()) >= 4:
            score += 3

    # 顺子检查
    is_shunzi = False
    for i in range(len(digits) - 2):
        if int(digits[i+1]) == int(digits[i]) + 1 and int(digits[i+2]) == int(digits[i]) + 2:
            is_shunzi = True
            break
    if is_shunzi:
        score += 8

    if score >= 85:
        grade = "A (大吉)"
    elif score >= 70:
        grade = "B (吉利)"
    elif score >= 55:
        grade = "C (一般)"
    elif score >= 40:
        grade = "D (较差)"
    else:
        grade = "E (凶)"

    recs = []
    if score < 60:
        recs.append(f"建议选尾数 {'/'.join(BEST_TAIL[wuxing])} 的号码")
    if "凶" in total_info[0]:
        recs.append("整体数理欠佳，建议换号")

    return {
        "号码": number_str,
        "纯数字": digits,
        "位数": len(digits),
        "尾号": digits[-4:] if len(digits) >= 4 else digits,
        "尾号五行": wuxing,
        "总分": min(score, 100),
        "等级": grade,
        "总格数理": {"数": total, "吉凶": total_info[0], "解读": total_info[1], "详解": total_info[2]},
        "后四位分析": {"数": tail_sum, "吉凶": tail_info[0], "解读": tail_info[1], "详解": tail_info[2]},
        "尾数": "吉" if tail_best else "平",
        "重复数字": {f"数字{d}": f"出现{cnt}次" for d, cnt in repeating.items()} if repeating else {},
        "顺子号": is_shunzi,
        "建议": recs,
    }


def print_haoma(data):
    """美化打印"""
    print("╔═══════════════════════════════════════════════╗")
    print("║             号 码 吉 凶 分 析                   ║")
    print("╠═══════════════════════════════════════════════╣")
    print(f"║ 号码: {data['号码']}")
    print(f"║ 评分: {data['总分']}分  ({data['等级']})")
    print("╠═══════════════════════════════════════════════╣")
    print(f"║ 位数: {data['位数']}位   尾号: {data['尾号']}")
    print(f"║ 五行: {data['尾号五行']}  尾数: {data['尾数']}")

    if data["顺子号"]:
        print(f"║ ⭐ 顺子号!")
    if data["重复数字"]:
        for k, v in data["重复数字"].items():
            print(f"║ ⭐ {k}: {v}")

    print("╠═══════════════════════════════════════════════╣")
    tg = data["总格数理"]
    print(f"║ 总格: {tg['数']} ({tg['吉凶']}) {tg['解读']}")
    wh = data["后四位分析"]
    print(f"║ 后四: {wh['数']} ({wh['吉凶']}) {wh['解读']}")
    print("╚═══════════════════════════════════════════════╝")

    if data["建议"]:
        print(f"\n  💡 建议: {'; '.join(data['建议'])}")

    print(f"\n  详细解读:")
    print(f"    {tg['详解']}")
    print(f"    {wh['详解']}")


