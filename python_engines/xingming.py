def calc_wuge(xing, ming1, ming2=""):
    """计算五格"""
    # 天格 = 姓笔画+1 (单姓) 或 姓笔画相加 (复姓)
    if isinstance(xing, tuple):
        tx = sum(xing)
        tian = tx  # 复姓: 直接相加
        ren = tx + get_stroke(ming1)  # 人格 = 姓合计+名1
    else:
        tx = xing if isinstance(xing, int) else get_stroke(xing)
        tian = tx + 1  # 单姓天格+1
        ren = tx + get_stroke(ming1)  # 人格

    # 地格
    if ming2:
        di = get_stroke(ming1) + get_stroke(ming2)
        zong = tian - 1 + di if not isinstance(xing, tuple) else sum(xing) + get_stroke(ming1) + get_stroke(ming2)
    else:
        di = get_stroke(ming1) + 1
        zong = tian - 1 + di if not isinstance(xing, tuple) else sum(xing) + get_stroke(ming1)

    # 外格 = 总格 - 人格 + 1
    wai = zong - ren + 1

    return {
        "天格": tian,
        "人格": ren,
        "地格": di,
        "外格": wai,
        "总格": zong,
    }


def analyze_wuge(wuge):
    """分析五格吉凶"""
    result = {}
    for name, num in wuge.items():
        info = SHULI_TABLE.get(num, ("未知",""))
        result[name] = {
            "数": num,
            "吉凶": info[0],
            "释义": info[1],
            "五行": num_to_wuxing(num),
        }
    return result


def analyze_sancai(wuge_analysis):
    """三才配置分析"""
    tx = wuge_analysis["天格"]["五行"]
    rx = wuge_analysis["人格"]["五行"]
    dx = wuge_analysis["地格"]["五行"]

    # 天→人→地 的生克关系
    tr = WUXING_RELATION.get((tx, rx), ("平",""))
    rd = WUXING_RELATION.get((rx, dx), ("平",""))

    config = f"{tx}→{rx}→{dx}"
    overall = ""
    if tr[0] == "吉" and rd[0] == "吉":
        overall = "大吉 — 三才配置优良，基础稳固，成功运佳"
    elif tr[0] == "凶" or rd[0] == "凶":
        overall = "凶 — 三才配置不理想，需注意健康或人际关系"
    else:
        overall = "平 — 三才配置尚可，中晚年运势较好"

    return {
        "配置": config,
        "天人": tr[1],
        "人地": rd[1],
        "总评": overall,
    }


def build_xingming_data(xing, ming1, ming2=""):
    """完整姓名学分析"""
    # 智能拆分：如果 ming1 是多字且 ming2 为空，自动拆分为名1+名2
    if len(ming1) > 1 and not ming2:
        ming2 = ming1[1:]
        ming1 = ming1[0]
    
    # 笔画
    sx = SURNAMES.get(xing)
    if sx is None:
        sx = get_stroke(xing)

    if isinstance(sx, tuple):
        xing_strokes = sum(sx)
    else:
        xing_strokes = sx

    ming1_strokes = get_stroke(ming1)
    ming2_strokes = get_stroke(ming2) if ming2 else 0

    # 五格
    wuge = calc_wuge(sx, ming1, ming2)

    # 五格分析
    wuge_analysis = analyze_wuge(wuge)

    # 三才
    sancai = analyze_sancai(wuge_analysis)

    # 总评
    total_score = 0
    for name, info in wuge_analysis.items():
        if "大吉" in info["吉凶"]:
            total_score += 20
        elif "半吉" in info["吉凶"] or "中吉" in info["吉凶"]:
            total_score += 12
        elif "凶带吉" in info["吉凶"]:
            total_score += 6

    if "大吉" in sancai["总评"]:
        total_score += 20
    elif "凶" in sancai["总评"]:
        total_score += 5
    else:
        total_score += 10

    if total_score >= 85:
        grade = "A (优秀)"
    elif total_score >= 70:
        grade = "B (良好)"
    elif total_score >= 55:
        grade = "C (一般)"
    else:
        grade = "D (较差)"

    return {
        "success": True,
        "姓名": f"{xing}{ming1}{ming2}",
        "姓": xing,
        "名1": ming1,
        "名2": ming2,
        "笔画": {
            "姓": sx if not isinstance(sx, tuple) else sx,
            "名1": ming1_strokes,
            "名2": ming2_strokes,
        },
        "五格": wuge,
        "五格分析": wuge_analysis,
        "三才": sancai,
        "评分": total_score,
        "等级": grade,
    }


