# 数理五行
def num_to_wuxing(n):
    """1-2木 3-4火 5-6土 7-8金 9-0水"""
    d = n % 10
    if d in [1,2]: return "木"
    if d in [3,4]: return "火"
    if d in [5,6]: return "土"
    if d in [7,8]: return "金"
    return "水"

